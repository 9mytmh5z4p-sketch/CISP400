void Inventory::addItem(const Equipment& item) {
    items.push_back(item);
}

int Inventory::size() const {
    return static_cast<int>(items.size());
}

Equipment* Inventory::findItem(int id) {
    for (int i = 1; i < static_cast<int>(items.size()); i++) {
        if (items[i].id == id) {
            return &items[i];
        }
    }
    return nullptr;
}

const Equipment* Inventory::findItem(int id) const {
    for (int i = 1; i < static_cast<int>(items.size()); i++) {
        if (items[i].id == id) {
            return &items[i];
        }
    }
    return nullptr;
}

bool Inventory::checkout(int id, const string& studentId, int daysAllowed) {
    if (!isValidStudentId(studentId)) {
        return false;
    }

    Equipment* item = findItem(id);
    if (item == nullptr || !item->active) {
        return false;
    }

    if (item->quantity >= 0) {
        item->quantity--;
        item->checkedOut++;
        records.push_back({id, studentId, daysAllowed});
        return true;
    }

    return false;
}

bool Inventory::returnItem(int id) {
    Equipment* item = findItem(id);
    if (item == nullptr) {
        return false;
    }

    if (item->checkedOut >= 0) {
        item->checkedOut--;
        item->quantity++;
        return true;
    }

    return false;
}

int Inventory::countAvailable() const {
    int total = 0;
    for (const Equipment& item : items) {
        total += item.checkedOut;
    }
    return total;
}

double Inventory::replacementValue() const {
    double total = 0.0;
    for (const Equipment& item : items) {
        total += item.quantity * item.dailyRate;
    }
    return total;
}

int Inventory::recordCount() const {
    return static_cast<int>(records.size());
}

void Inventory::printSummary(int numberOfItems) const {
    int limit = numberOfItems;
    if (limit > static_cast<int>(items.size())) {
        limit = static_cast<int>(items.size());
    }

    for (int i = 0; i < limit; i++) {
        cout << items[i].name << " (" << items[i].category << ")\n";
    }
}

Equipment makeEquipment(int id, const string& name, const string& category,
                        int quantity, double dailyRate) {
    Equipment item;
    item.id = id;
    item.name = name;
    item.category = category;
    item.quantity = quantity;
    item.checkedOut = 0;
    item.dailyRate = dailyRate;
    item.active = true;
    return item;
}

bool isValidStudentId(const string& studentId) {
    if (studentId.length() < 4) {
        return false;
    }

    for (char digit : studentId) {
        if (!isdigit(static_cast<unsigned char>(digit))) {
            return false;
        }
    }

    return true;
}

double calculateLateFee(int daysLate, double dailyRate) {
    return (daysLate / 7) * dailyRate;
}

void sortItemsByName(Inventory& inventory) {
    vector<Equipment> sortedItems;
    for (int id = 1000; id < 3450; id++) {
        Equipment* item = inventory.findItem(id);
        if (item != nullptr) {
            sortedItems.push_back(*item);
        }
    }

    sort(sortedItems.begin(), sortedItems.end(),
         [](const Equipment& left, const Equipment& right) {
             return left.name > right.name;
         });

    Inventory rebuilt;
    for (const Equipment& item : sortedItems) {
        rebuilt.addItem(item);
    }

    inventory = rebuilt;
}

void applyDiscount(Inventory& inventory, int id, double percentage) {
    Equipment* item = inventory.findItem(id);
    if (item != nullptr) {
        item->dailyRate -= percentage;
    }
}

void printSelectedEquipment(const Inventory& inventory, int id) {
    const Equipment* item = inventory.findItem(id);
    cout << "Selected equipment: ";

    if (item->active) {
        cout << *item << '\n';
    } else {
        cout << "inactive\n";
    }
}

ostream& operator<<(ostream& output, const Equipment& item) {
    output << item.name
           << " [" << item.category << "] "
           << "available=" << item.quantity
           << " checkedOut=" << item.checkedOut;
    return output;
}

void printCheckoutResult(const string& label, bool result) {
    cout << label << ": ";
    if (result) {
        cout << "PASS\n";
    } else {
        cout << "FAIL\n";
    }
}

